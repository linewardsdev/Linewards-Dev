def write_wav(path: Path, data: np.ndarray, rate: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pcm = (np.clip(data, -1, 1) * 32767).astype("<i2")
    channels = 1 if pcm.ndim == 1 else pcm.shape[1]
    with wave.open(str(path), "wb") as f:
        f.setnchannels(channels)
        f.setsampwidth(2)
        f.setframerate(rate)
        f.writeframes(pcm.tobytes())


def all_expected_files() -> list[str]:
    return [variant for name, sound in SFX.items() for variant in variant_names(name, sound)]


def verify() -> int:
    failures = []
    for variant in all_expected_files():
        path = SFX_DIR / f"{variant}.wav"
        if not path.exists():
            failures.append(f"{variant}: missing")
            continue
        with wave.open(str(path)) as f:
            raw = np.frombuffer(f.readframes(f.getnframes()), dtype="<i2") / 32767.0
        peak, dc = np.max(np.abs(raw)), abs(float(np.mean(raw)))
        if not 0.05 <= peak <= 0.8:
            failures.append(f"{variant}: peak {peak:.3f} outside mix policy")
        if dc > 0.01:
            failures.append(f"{variant}: DC offset {dc:.4f}")
        if abs(raw[0]) > 0.02 or abs(raw[-1]) > 0.02:
            failures.append(f"{variant}: does not start/end near zero (click)")

    path = MUSIC_DIR / "music_bed_loop.wav"
    if path.exists():
        with wave.open(str(path)) as f:
            raw = np.frombuffer(f.readframes(f.getnframes()), dtype="<i2").reshape(-1, 2) / 32767.0
        seam = float(np.max(np.abs(raw[0] - raw[-1])))
        step = float(np.max(np.abs(np.diff(raw[:, 0]))))
        if seam > step * 2:
            failures.append(f"music: seam discontinuity {seam:.4f} exceeds 2x max in-loop step {step:.4f}")
    else:
        failures.append("music: missing")

    for line in failures:
        print(f"FAIL  {line}")
    print(f"{'FAILED' if failures else 'OK'}: {len(all_expected_files())} sfx files + music checked, {len(failures)} problem(s)")
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true", help="check existing files instead of writing")
    args = parser.parse_args()
    if args.verify:
        return verify()

    for name, sound in SFX.items():
        for variant in variant_names(name, sound):
            data = render(name, variant, sound)
            write_wav(SFX_DIR / f"{variant}.wav", data, SFX_RATE)
            print(f"wrote {variant}.wav  ({len(data) / SFX_RATE:.2f}s, peak {np.max(np.abs(data)):.2f})")
    music = music_bed()
    write_wav(MUSIC_DIR / "music_bed_loop.wav", music, MUSIC_RATE)
    print(f"wrote music_bed_loop.wav  ({MUSIC_SECONDS:.0f}s stereo, "
          f"{(MUSIC_DIR / 'music_bed_loop.wav').stat().st_size / 1e6:.1f} MB)")
    return 0



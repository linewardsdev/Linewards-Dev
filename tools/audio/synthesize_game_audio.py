#!/usr/bin/env python3
"""Generates every audio asset in the project, deterministically.

LAUNCH_ROADMAP P0 item 3: the game's audio was seven procedural sine beeps and zero audio
asset files. This script is the fix's foundation: it synthesizes a full cue set plus an
ambient music bed as ordinary WAV files that Unity imports like any authored asset.

Why synthesis rather than sourced audio: nothing here can license a sound library, and
committed binaries that cannot be regenerated from the repo are a defect this project has
already been bitten by (OPEN_ITEMS item 18, eleven unregenerable texture maps). Every WAV
this writes is reproducible bit-for-bit from this file — change a sound by editing its
function and re-running, never by editing a WAV.

--------------------------------------------------------------------------------------
The second pass ("sounds good, just basic"), and what it added
--------------------------------------------------------------------------------------
The first pass was dry additive synthesis: correct, coherent, and audibly generated. The
owner's verdict was exactly that, so this pass closes the three gaps that make the
difference between *synthesized* and *produced*:

- SPACE. Every cue now passes through a small Schroeder reverb, tuned per family and baked
  into the file — a tight metallic room for FOUNDRY, an airier hall for GROVE, a shimmer
  for ARCANE, a long dark tail for the stings. Dryness was the single loudest tell that a
  sound came from a generator, and baking the space costs nothing at runtime.

- ONE KEY. The music bed is D minor; the cues used to be pitched wherever convenient. Every
  tonal cue is now built from the NOTE table below — confirmations on the D tonic, victory
  on the relative major (F), the leak alarm on the in-key maximal dissonance (Bb against A).
  A soundscape that agrees with itself is most of what "designed" means.

- REAL INSTRUMENTS where the sines were thinnest. GROVE shots are Karplus-Strong plucked
  strings (a physical model — an excited delay line IS a string, so it sounds like wood
  and tension rather than an oscillator). Impacts and the foundry ring are modal synthesis:
  a bank of exponentially-decaying resonant modes, which is how struck objects actually
  behave. Ratios for metal are deliberately inharmonic.

- VARIANTS. Constant cues (shots, hits, kills, snare) now ship 2-3 takes each, generated by
  jittering synthesis parameters under per-variant seeds. The director round-robins them;
  pitch jitter alone cannot hide sample repetition in a long fight.

Mix intent, unchanged from the first pass:
  - Cues that fire constantly (shots, hits) peak low (~0.14-0.18).
  - Cues that mean money or progress (income, build) sit mid (~0.3).
  - Cues that demand attention (leak, elimination, match end) peak high (~0.5-0.75).
  - The music bed peaks ~0.3 and must stay under everything - it is a floor, not a voice.
  Reverb is renormalized back to each cue's pre-verb peak, so space never changes loudness.

Loop correctness for the music bed is constructed, not hoped for: every tonal oscillator's
frequency is quantized to a whole number of cycles per loop, so phase at the seam equals
phase at zero; the noise layer is seam-crossfaded. `--verify` checks the seam numerically
along with peaks, DC offset and edge clicks, across every variant file.
"""


def _rng_for(name: str) -> np.random.Generator:
    """Every sound VARIANT gets its own generator, seeded from its full name.

    A single shared RNG was the first version, and it made a lie of this file's editing
    promise: noise() draws from the stream in call order, so ADDING a sound shifted the
    draws for every sound generated after it. Per-name seeding makes edits isolated:
    touching one sound's function can only ever change that sound's files."""
    return np.random.default_rng(20260803 + int.from_bytes(name.encode()[:8].ljust(8, b'\0'), 'big') % 1000003)


RNG = _rng_for("default")  # rebound per variant by main() and by music_bed()



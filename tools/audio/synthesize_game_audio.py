@dataclass(frozen=True)
class Sound:
    """A cue: its synthesis function, how many takes to generate, and its baked space.

    Space is (wet, decay_seconds, size). Families share rooms on purpose - FOUNDRY cues in
    a tight metallic chamber, GROVE in an airier hall, ARCANE with a shimmering mid room,
    stings in a long dark hall - so the mix sounds like one place per family rather than
    seventeen unrelated boxes."""
    fn: object
    variants: int = 1
    space: tuple[float, float, float] | None = None


